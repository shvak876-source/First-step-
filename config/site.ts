/** האם מחיר ההשקה בתוקף בתאריך הנתון. מחושב תמיד בשרת בעת יצירת התשלום. */
export function isLaunchActive(now: Date = new Date()): boolean {
  return now.getTime() < new Date(pricing.launchEndsAt).getTime();
}

export function currentPrice(now: Date = new Date()): number {
  return isLaunchActive(now) ? pricing.launchPrice : pricing.regularPrice;
}

export function formatDateHe(iso: string | Date): string {
  return new Intl.DateTimeFormat("he-IL", {
    timeZone: "Asia/Jerusalem",
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  }).format(typeof iso === "string" ? new Date(iso) : iso);
}

export function formatPrice(n: number): string {
  return `${n.toLocaleString("he-IL")} ₪`;
}
